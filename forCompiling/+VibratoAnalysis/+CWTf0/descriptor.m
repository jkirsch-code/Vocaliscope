function d = descriptor()
%DESCRIPTOR Returns specification for CWT-of-f0 vibrato analysis method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'CWT of F0 Contour';
d.acronym = 'CWTF0';
d.summary = 'CWT of F0 contour for rate + F0-derived extent (bandpass + Hilbert envelope).';
d.details = sprintf([ ...
    'This method uses the Continuous Wavelet Transform (CWT) of the ' ...
    'interpolated F0 contour for rate detection, and the F0 contour ' ...
    'directly (bandpass filter + Hilbert envelope) for extent.\n\n' ...
    'Algorithm:\n' ...
    '1. Pitch extraction (SWIPE'' or user-selected method)\n' ...
    '2. Interpolate F0 contour to uniform time grid\n' ...
    '3. Compute CWT of centered F0 Hz using Morlet wavelet (fCWT library)\n' ...
    '4. Find peak frequency at each time step (vibrato speed)\n' ...
    '5. Convert F0 to cents, bandpass filter at vibrato range\n' ...
    '6. Hilbert envelope gives instantaneous extent (half-extent, ± cents)\n' ...
    '7. Filter by minimum/maximum speed and minimum extent\n\n' ...
    'Key outputs:\n' ...
    '- Vibrato speed (Hz): instantaneous modulation frequency from CWT\n' ...
    '- Vibrato extent (cents): instantaneous modulation depth from F0 contour\n' ...
    '- Time-frequency map: 2D CWT representation\n\n' ...
    'Uses fCWT library (Arts & van den Broek, 2022) for fast CWT computation.\n' ...
    'Extent computed from F0 contour (not CWT amplitude) because the CWT ' ...
    'coefficient magnitude depends on wavelet normalization and does not ' ...
    'reliably map to Hz.\n\n' ...
    'Minimum sample rate: 8 kHz (for pitch detection).']);

d.inputTypes = {'Audio'};
d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Acoustic signal for pitch extraction and CWT analysis');
d.voiceTypes = {'modal', 'breathy', 'pressed'};
d.instrumentTypes = {'violin', 'cello', 'flute', 'saxophone', 'voice'};
d.validatedFor = 'General vibrato analysis (Morlet CWT of F0 contour)';
d.minFs_Hz = 8000;
d.algorithmDesc = 'Morlet CWT for rate + F0 bandpass/Hilbert for extent (half-extent ±)';

d.params = struct(...
    'fMin',              {struct('default', 0.01, 'limits', [0.001 1], 'tooltip', 'Minimum vibrato modulation frequency for CWT analysis (Hz)')}, ...
    'fMax',              {struct('default', 15, 'limits', [5 30], 'tooltip', 'Maximum vibrato modulation frequency for CWT analysis (Hz)')}, ...
    'c0',                {struct('default', 5, 'limits', [1 20], 'tooltip', 'Morlet wavelet parameter (higher = better frequency resolution)')}, ...
    'voicesPerOctave',   {struct('default', 48, 'limits', [12 192], 'tooltip', 'Number of frequency bins per octave for CWT resolution')}, ...
    'minSpeedHz',        {struct('default', 2, 'limits', [0.5 5], 'tooltip', 'Minimum vibrato speed to consider valid (Hz)')}, ...
    'maxSpeedHz',        {struct('default', 12, 'limits', [8 20], 'tooltip', 'Maximum vibrato speed to consider valid (Hz)')}, ...
    'minExtent_cents',   {struct('default', 5, 'limits', [1 50], 'tooltip', 'Minimum vibrato extent to consider valid (cents)')});

end
