function vibratoMethods = vibratoDescriptions()
%VIBRATODESCRIPTIONS Returns registry of all vibrato analysis methods
%   vibratoMethods = VIBRATODESCRIPTIONS() returns a struct array with
%   metadata for each vibrato analysis method available in the package.

vibratoMethods = struct('id', {}, 'name', {}, 'acronym', {}, 'descriptor', {}, 'sources', {});

% --- VibratoToolbox (Hilbert AM/FM) ---
try
    vatDesc = VibratoAnalysis.VibratoToolbox.descriptor();
    vatSources = VibratoAnalysis.VibratoToolbox.sources();
    vibratoMethods(end+1) = struct(...
        'id', 'VAT', ...
        'name', vatDesc.name, ...
        'acronym', vatDesc.acronym, ...
        'descriptor', vatDesc, ...
        'sources', vatSources);
catch ME
    warning('VibratoAnalysis: Could not load VibratoToolbox descriptor: %s', ME.message);
end

% --- AVA (FDM-based) ---
try
    avaDesc = VibratoAnalysis.AVA.descriptor();
    avaSources = VibratoAnalysis.AVA.sources();
    vibratoMethods(end+1) = struct(...
        'id', 'AVA', ...
        'name', avaDesc.name, ...
        'acronym', avaDesc.acronym, ...
        'descriptor', avaDesc, ...
        'sources', avaSources);
catch ME
    warning('VibratoAnalysis: Could not load AVA descriptor: %s', ME.message);
end

% --- VibratoScope (Cycle-based) ---
try
    vsDesc = VibratoAnalysis.VibratoScope.descriptor();
    vsSources = VibratoAnalysis.VibratoScope.sources();
    vibratoMethods(end+1) = struct(...
        'id', 'VIBSCOPE', ...
        'name', vsDesc.name, ...
        'acronym', vsDesc.acronym, ...
        'descriptor', vsDesc, ...
        'sources', vsSources);
catch ME
    warning('VibratoAnalysis: Could not load VibratoScope descriptor: %s', ME.message);
end

% --- CWTf0 (CWT of F0 contour) ---
try
    cwtDesc = VibratoAnalysis.CWTf0.descriptor();
    cwtSources = VibratoAnalysis.CWTf0.sources();
    vibratoMethods(end+1) = struct(...
        'id', 'CWTF0', ...
        'name', cwtDesc.name, ...
        'acronym', cwtDesc.acronym, ...
        'descriptor', cwtDesc, ...
        'sources', cwtSources);
catch ME
    warning('VibratoAnalysis: Could not load CWTf0 descriptor: %s', ME.message);
end

end
