function d = descriptor()
%DESCRIPTOR Returns specification for VibratoToolbox method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'Vibrato Analysis Toolbox (Hilbert AM/FM)';
d.acronym = 'VAT';
d.summary = 'Hilbert transform-based AM/FM analysis for vibrato characterization from high-precision magnitude/frequency tracking.';
d.details = sprintf([ ...
    'The Vibrato Analysis Toolbox (VAT) uses the Hilbert transform to extract ' ...
    'amplitude modulation (AM) and frequency modulation (FM) from audio signals. ' ...
    'This method isolates harmonic partials via bandpass filtering, then applies ' ...
    'the Hilbert transform to obtain the analytic signal, from which instantaneous ' ...
    'amplitude and frequency are extracted.\n\n' ...
    'Algorithm (Zhang et al. 2017):\n' ...
    '1. Bandpass filter to isolate harmonic partials (F0-adaptive filtering)\n' ...
    '2. Hilbert transform to obtain analytic signal\n' ...
    '3. Extract instantaneous amplitude (AM envelope)\n' ...
    '4. Extract instantaneous frequency (FM trajectory)\n' ...
    '5. Compute modulation indices for AM and FM\n' ...
    '6. Analyze AM/FM phase relationship and time delay\n' ...
    '7. Estimate vibrato parameters: depth, rate, spectral centroid\n\n' ...
    'Key parameters extracted:\n' ...
    '- AM modulation index (vibrato depth in amplitude)\n' ...
    '- FM modulation index (vibrato depth in frequency)\n' ...
    '- AM/FM phase relationship\n' ...
    '- Time delay between AM and FM peaks\n' ...
    '- Spectral centroid variations\n\n' ...
    'Validated for singing voices, bowed string instruments, and wind instruments.\n\n' ...
    'LIMITATION: Uses global autocorrelation for F0 estimation (single value ' ...
    'for entire signal). Works well for single-vibrato segments (5-10 s). ' ...
    'Multi-note recordings produce incorrect F0, causing bandpass to kill ' ...
    'the signal. Use CWTf0 or VibratoScope for multi-note analysis.\n\n' ...
    'Minimum sample rate: 8 kHz.']);

d.inputTypes = {'Audio'};
d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Acoustic signal for Hilbert AM/FM extraction');
d.voiceTypes = {'modal', 'breathy', 'pressed'};
d.instrumentTypes = {'violin', 'cello', 'flute', 'saxophone', 'voice'};
d.validatedFor = 'Singing voices, bowed string instruments, wind instruments (Zhang et al. 2017, JAES)';
d.minFs_Hz = 8000;
d.algorithmDesc = 'Hilbert AM/FM decomposition with modulation depth estimation';

d.params = struct(...
    'bpLowScale',     {struct('default', 0.6, 'limits', [0.1 1.0], 'tooltip', 'Bandpass filter low cutoff as fraction of estimated F0')}, ...
    'bpHighScale',    {struct('default', 1.4, 'limits', [1.0 3.0], 'tooltip', 'Bandpass filter high cutoff as fraction of estimated F0')}, ...
    'smoothWindow_s', {struct('default', 0.05, 'limits', [0.01 0.2], 'tooltip', 'Smoothing window for AM/FM envelopes (seconds)')}, ...
    'minModIndex',    {struct('default', 0.01, 'limits', [0.001 0.1], 'tooltip', 'Minimum modulation index threshold for vibrato detection')});

end
