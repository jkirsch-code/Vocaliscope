function d = descriptor()
%DESCRIPTOR Returns specification for VibratoScope cycle-based method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'VibratoScope (Cycle-Based)';
d.acronym = 'VIBSCOPE';
d.summary = 'Cycle-based vibrato analysis with jitter, shimmer, and entropy metrics.';
d.details = sprintf([ ...
    'VibratoScope (Cruz, 2025) performs cycle-based analysis of vibrato, ' ...
    'extracting rate, extent, jitter, and regularity metrics from pitch contours.\n\n' ...
    'Algorithm (rewritten from Python reference implementation):\n' ...
    '1. Pitch extraction (SWIPE'' or user-selected method)\n' ...
    '2. Convert to cents relative to median pitch\n' ...
    '3. Bandpass filter (3-9 Hz) to isolate vibrato modulation\n' ...
    '4. Detect peaks and troughs in filtered contour\n' ...
    '5. Pair consecutive extrema into vibrato half-cycles\n' ...
    '6. Extract per-cycle parameters: rate, extent, center pitch\n' ...
    '7. Compute statistics: mean/median rate/extent, jitter, CV\n' ...
    '8. Compute Sample Entropy for regularity assessment\n\n' ...
    'Key metrics:\n' ...
    '- Vibrato rate (Hz): 1 / (2 * cycle_time)\n' ...
    '- Vibrato extent (cents): half peak-to-trough amplitude\n' ...
    '- Jitter: cycle-to-cycle period variability\n' ...
    '- CV: coefficient of variation for rate and extent\n' ...
    '- SampEn: sample entropy (regularity)\n\n' ...
    'Reference: Cruz, T. L. B. (2025). VibratoScope: A Python Toolkit for ' ...
    'High-Resolution Vibrato Analysis in Singing Voice. Zenodo.\n\n' ...
    'Minimum sample rate: 8 kHz (for pitch detection).']);

d.inputTypes = {'Audio'};
d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Acoustic signal for pitch detection and cycle analysis');
d.voiceTypes = {'modal', 'breathy', 'pressed'};
d.instrumentTypes = {'violin', 'cello', 'flute', 'saxophone', 'voice'};
d.validatedFor = 'Singing voice (Cruz, 2025)';
d.minFs_Hz = 8000;
d.algorithmDesc = 'Cycle-based analysis with Butterworth bandpass filtering and peak/trough detection';

d.params = struct(...
    'bpLowHz',           {struct('default', 3.0, 'limits', [1 6], 'tooltip', 'Low cutoff frequency for vibrato bandpass filter (Hz)')}, ...
    'bpHighHz',          {struct('default', 9.0, 'limits', [5 15], 'tooltip', 'High cutoff frequency for vibrato bandpass filter (Hz)')}, ...
    'bpOrder',           {struct('default', 4, 'limits', [2 8], 'tooltip', 'Butterworth filter order')}, ...
    'peakProminence',    {struct('default', 1.0, 'limits', [0.1 20], 'tooltip', 'Minimum peak prominence in cents for detection')}, ...
    'peakDistance',       {struct('default', 3, 'limits', [2 20], 'tooltip', 'Minimum distance between peaks in samples')}, ...
    'minHalfExtent',     {struct('default', 0.5, 'limits', [0.1 50], 'tooltip', 'Minimum half-extent in cents to keep a cycle')}, ...
    'maxHalfExtent',     {struct('default', 300.0, 'limits', [50 600], 'tooltip', 'Maximum half-extent in cents to keep a cycle')}, ...
    'outlierThreshold',  {struct('default', 5.0, 'limits', [2 10], 'tooltip', 'MAD threshold for pitch outlier removal')}, ...
    'resampleFs',        {struct('default', 100, 'limits', [50 200], 'tooltip', 'Resampling rate for uniform pitch grid (Hz)')}, ...
    'sampEnM',           {struct('default', 2, 'limits', [1 4], 'tooltip', 'Embedding dimension for Sample Entropy')}, ...
    'sampEnR',           {struct('default', 0, 'limits', [0 1], 'tooltip', 'Tolerance for Sample Entropy (0 = auto 0.2*std)')});

end
