function d = descriptor()
%DESCRIPTOR Returns specification for AVA (FDM-based) method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'Automatic Vibrato Analysis (FDM)';
d.acronym = 'AVA';
d.summary = 'Filter Diagonalisation Method for high-resolution vibrato rate and extent estimation.';
d.details = sprintf([ ...
    'AVA (Automatic Vibrato and Portamento Analysis) uses the Filter ' ...
    'Diagonalisation Method (FDM) for high-resolution frequency estimation ' ...
    'of vibrato modulation. FDM provides super-resolution frequency analysis ' ...
    'that can distinguish closely-spaced frequency components.\n\n' ...
    'Algorithm (Yang et al. 2016, 2017):\n' ...
    '1. Pitch detection (YIN) to extract F0 contour\n' ...
    '2. Convert to MIDI scale and smooth\n' ...
    '3. Frame-wise FDM analysis (125ms frames, 25%% overlap)\n' ...
    '4. For each frame: construct Toeplitz-like matrices, solve eigenvalue problem\n' ...
    '5. Extract dominant resonance: frequency = vibrato rate, amplitude = extent\n' ...
    '6. Classify vibrato frames using Decision Tree threshold\n' ...
    '7. Segment consecutive vibrato frames into vibrato regions\n' ...
    '8. Extract parameters: rate, extent, sinusoidal similarity\n\n' ...
    'Key parameters extracted:\n' ...
    '- Vibrato rate (Hz) from FDM frequency estimation\n' ...
    '- Vibrato extent (semitones) from FDM amplitude\n' ...
    '- Sinusoidal similarity via cross-correlation\n' ...
    '- Individual vibrato region boundaries\n\n' ...
    'FDM provides higher frequency resolution than FFT-based methods, ' ...
    'making it suitable for analyzing vibrato with closely-spaced modulation ' ...
    'components or short duration.\n\n' ...
    'Validated for singing voices and bowed string instruments.\n\n' ...
    'Minimum sample rate: 8 kHz (for pitch detection).']);

d.inputTypes = {'Audio'};
d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Acoustic signal for pitch detection and FDM analysis');
d.voiceTypes = {'modal', 'breathy', 'pressed'};
d.instrumentTypes = {'violin', 'cello', 'flute', 'saxophone', 'voice'};
d.validatedFor = 'Singing voices, bowed string instruments (Yang et al. 2016, ISMIR; Yang et al. 2017, JMM)';
d.minFs_Hz = 8000;
d.algorithmDesc = 'Filter Diagonalisation Method (FDM) with Decision Tree classification';

d.params = struct(...
    'fMin',              {struct('default', 2, 'limits', [1 10], 'tooltip', 'Minimum vibrato rate for detection (Hz)')}, ...
    'fMax',              {struct('default', 12, 'limits', [5 20], 'tooltip', 'Maximum vibrato rate for detection (Hz)')}, ...
    'amplitudeMin',      {struct('default', 0.0001, 'limits', [0.00001 0.1], 'tooltip', 'Minimum amplitude threshold for vibrato detection')}, ...
    'frameLength_s',     {struct('default', 1.0, 'limits', [0.5 3.0], 'tooltip', 'FDM analysis frame length (seconds)')}, ...
    'frameOverlap',      {struct('default', 0.5, 'limits', [0.1 0.75], 'tooltip', 'Frame overlap fraction (0-1)')}, ...
    'kMax',              {struct('default', 6, 'limits', [2 15], 'tooltip', 'Maximum number of FDM iterations')}, ...
    'minVibratoFrames',  {struct('default', 2, 'limits', [1 10], 'tooltip', 'Minimum consecutive vibrato frames for valid detection')});

end
