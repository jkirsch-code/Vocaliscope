function d = descriptor()
%DESCRIPTOR Returns specification for Vocal Attack Time (VAT) method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'Vocal Attack Time (Audio+EGG)';
d.acronym = 'VAT';
d.summary = 'Time lag between the audio (SP) envelope and the EGG envelope at phonation onset; positive = soft onset, negative = hard onset';
d.details = sprintf([ ...
    'Vocal Attack Time (VAT) measures the temporal coordination between ' ...
    'the acoustic signal and the electroglottographic (EGG) signal at ' ...
    'phonation onset. It is defined as the cross-correlation lag between ' ...
    'the Hilbert envelopes of the band-pass filtered SP and EGG signals. ' ...
    'A positive VAT (SP leads EGG) indicates a soft/breathy onset where ' ...
    'airflow begins before full vocal fold adduction. A negative VAT (EGG ' ...
    'leads SP) indicates a hard/glottal onset where vocal fold contact ' ...
    'precedes acoustic output.\n\n' ...
    'Algorithm (Roark 2012, Watson 2015): F0 is estimated via ' ...
    'autocorrelation of the EGG signal in the stable phonation region ' ...
    '(50-500 ms post-onset). F0-adaptive band-pass filter (F0 x 0.6 to ' ...
    'F0 x 1.4) is applied to both signals -> Hilbert envelope (analytic ' ...
    'signal magnitude) -> Gaussian smoothing (N pitch periods) -> ' ...
    'F0-adaptive difference function A''(t) = A(t) - A(t - N/F0) -> ' ...
    'cross-correlation of SP vs EGG difference functions within ' ...
    '±maxLag_s -> parabolic sub-sample peak interpolation -> Figure of ' ...
    'Merit (Pearson r at optimal lag; threshold >0.75).\n\n' ...
    'When only an audio signal is provided, a synthetic EGG is generated ' ...
    'internally via differentiation and rectification (not suitable for ' ...
    'clinical use with recorded EGG).\n\n' ...
    'Validated for modal phonation in healthy adults.\n\n' ...
    'In synchronous EGG+audio recordings, VAT includes a fixed acoustic ' ...
    'delay of ~0.5–1.0ms caused by sound travelling from the vocal folds ' ...
    'to the microphone. This is a systematic bias in all reported VAT ' ...
    'values. The literature reports raw VAT without correction (Orlikoff ' ...
    '2009, Roark 2012). Relative comparisons (pre/post treatment, soft vs ' ...
    'hard onset) are unaffected.\n\n' ...
    'Minimum sample rate: 8 kHz.']);

d.requiredSignals = {'Audio'};
d.optionalSignals = {'EGG'};
d.signalRoles = struct(...
    'Audio', 'Acoustic speech pressure signal for envelope cross-correlation', ...
    'EGG', 'Electroglottographic signal for laryngeal onset measurement (optional; synthetic EGG used when not provided)');
d.voiceTypes = {'modal'};
d.onsetTypes = {'soft', 'hard', 'breathy'};
d.validatedFor = 'Healthy adults (Orlikoff et al. 2009, J. Voice; Roark et al. 2012, J. Voice)';
d.minFs_Hz = 8000;
d.algorithmDesc = 'F0-adaptive BP filter + envelope diff functions + xcorr (Roark 2012, Watson 2015)';

d.params = struct(...
    'f0BandpassLowScale',  {struct('default',0.6, 'limits',[0.1 1.0], 'tooltip','BP filter low cutoff as fraction of estimated F0')}, ...
    'f0BandpassHighScale', {struct('default',1.4, 'limits',[1.0 3.0], 'tooltip','BP filter high cutoff as fraction of estimated F0')}, ...
    'smoothPeriods',       {struct('default',2.0, 'limits',[0.5 10],  'tooltip','Gaussian smoothing window in pitch periods')}, ...
    'diffLagPeriods',      {struct('default',2.0, 'limits',[0.5 10],  'tooltip','Difference function lag in pitch periods')}, ...
    'maxLag_s',            {struct('default',0.02,'limits',[0.002 0.05],'tooltip','Maximum cross-correlation lag for VAT search (s)')}, ...
    'fomThreshold',        {struct('default',0.75,'limits',[0.1 0.99],'tooltip','Minimum Figure of Merit (Pearson r) for reliable VAT estimate')}, ...
    'maxWindow_s',         {struct('default',0.3, 'limits',[0.05 2.0], 'tooltip','Maximum post-onset analysis window (s); limits the F0 estimation segment')});

end
