function d = descriptor()
d.name = 'Phonation Onset Time - Mergell (Audio)';
d.acronym = 'POT_M';
d.summary = 'Time for amplitude envelope to grow from 32.2% to 67.8% of steady-state amplitude, estimated via Mergell growth function fit to the continuous Hilbert envelope (classic approach, optimal for Audio)';
d.details = sprintf([ ...
    'Phonation Onset Time - Mergell (POT-M) measures the duration of exponential ' ...
    'amplitude growth from 32.2% to 67.8% of the steady-state (saturation) ' ...
    'amplitude, applied to the continuous Hilbert envelope of the signal. ' ...
    'This is the classic Mergell approach, best suited for Audio signals ' ...
    'where the Hilbert envelope is smooth and free of F0 ripple.\n\n' ...
    'Algorithm: Hilbert envelope (full-band or HP-filtered) -> Gaussian ' ...
    'smoothing -> crop to first 40%% for onset -> grid search fit of ' ...
    'Mergell growth function r(t) = r0 * ((1 - (r0/rf)^2) * exp(-2*a*t) ' ...
    '+ (r0/rf)^2)^(-1/2) -> POT = 1/a (time constant corresponding to ' ...
    '32.2%%-67.8%% rise).\n\n' ...
    'For EGG or airflow signals, use POT-Petermann instead, which fits ' ...
    'the growth function to discrete cycle peaks to avoid F0 ripple ' ...
    'artifacts.\n\n' ...
    'Reference implementation follows Mergell et al. (1998) and Patel ' ...
    'et al. (2017) with integer grid search over a = 1..500 and rf values, ' ...
    'minimizing MSE.\n\n' ...
    'Minimum sample rate: 1 kHz (prefer 8+ kHz for envelope resolution).']);

d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Audio signal for continuous Hilbert envelope analysis (optimal)');
d.voiceTypes = {'modal', 'breathy'};
d.onsetTypes = {'soft', 'breathy'};
d.validatedFor = 'Mergell et al. (1998, JASA); Patel et al. (2017, J Voice)';
d.minFs_Hz = 1000;
d.algorithmDesc = 'Hilbert envelope + Mergell growth function grid search (continuous envelope)';

d.params = struct(...
    'smoothWindow_s', {struct('default',0.02, 'limits',[0.005 0.05], 'tooltip','Gaussian smoothing window for Hilbert envelope (s)')}, ...
    'maxWindow_s',    {struct('default',0.3, 'limits',[0.05 2.0], 'tooltip','Maximum post-onset analysis window (s); limits data used for steady-state estimation and crop')});

end
