function onsetMethods = onsetDescriptions()
onsetMethods = struct('id', {}, 'name', {}, 'acronym', {}, 'descriptor', {}, 'sources', {});

% --- VRT ---
try
    vrtDesc = OnsetAnalysis.VRT.descriptor();
    vrtSources = OnsetAnalysis.VRT.sources();
    onsetMethods(end+1) = struct(...
        'id', 'VRT', ...
        'name', vrtDesc.name, ...
        'acronym', vrtDesc.acronym, ...
        'descriptor', vrtDesc, ...
        'sources', vrtSources);
catch ME
    warning('OnsetAnalysis: Could not load VRT descriptor: %s', ME.message);
end

