function d = descriptor()
d.name = 'Phonation Onset Time - Petermann (All signals)';
d.acronym = 'POT_P';
d.summary = 'Time for amplitude envelope to grow from 32.2% to 67.8% of steady-state amplitude, estimated via Mergell growth function fit to discrete cycle peak amplitudes after F0-adaptive narrow bandpass filtering';
d.details = sprintf([ ...
    'Phonation Onset Time - Petermann (POT-P) measures the duration of ' ...
    'exponential amplitude growth from 32.2%% to 67.8%% of the steady-state ' ...
    '(saturation) amplitude, using the cycle-peak fitting approach ' ...
    'recommended by Petermann et al. (2016). Unlike the classic Mergell ' ...
    'method (POT-M), which fits to the continuous Hilbert envelope, POT-P ' ...
    'operates on discrete cycle peak amplitudes extracted from an ' ...
    'F0-adaptive narrow bandpass filter. This avoids F0 ripple artifacts ' ...
    'on EGG and airflow signals while remaining equally valid for Audio.\n\n' ...
    'Algorithm:\n' ...
    '1. F0 estimation via autocorrelation from post-onset segment\n' ...
    '2. Narrow bandpass filter at F0 x [0.9, 1.1]\n' ...
    '3. Cycle peak detection (findpeaks with min distance = 0.5/F0)\n' ...
    '4. Onset/steady-state region detection from peak amplitudes\n' ...
    '5. Grid search fit of Mergell growth function to discrete peak amplitudes\n' ...
    '6. POT = 1/a (time constant corresponding to 32.2%%-67.8%% rise)\n\n' ...
    'Reference implementation follows Petermann et al. (2016) and the ' ...
    'VOAT open-source toolkit (Arias-Vergara et al. 2024).\n\n' ...
    'Suitable for all signal types: Audio, EGG, Airflow, and GAW.\n\n' ...
    'Minimum sample rate: 1 kHz (prefer 8+ kHz for envelope resolution).']);

d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Any amplitude envelope signal: Audio, EGG, Airflow, or GAW');
d.voiceTypes = {'modal', 'breathy'};
d.onsetTypes = {'soft', 'breathy', 'hard'};
d.validatedFor = 'Petermann et al. (2016, CMMM); Arias-Vergara et al. (2024, SoftwareX)';
d.minFs_Hz = 1000;
d.algorithmDesc = 'F0-adaptive narrow BP + cycle peaks + Mergell growth function grid search';

d.params = struct(...
    'bpLowScale',  {struct('default',0.9, 'limits',[0.5 1.0], 'tooltip','Narrow bandpass low cutoff as fraction of F0')}, ...
    'bpHighScale', {struct('default',1.1, 'limits',[1.0 2.0], 'tooltip','Narrow bandpass high cutoff as fraction of F0')}, ...
    'maxWindow_s', {struct('default',0.3, 'limits',[0.05 2.0], 'tooltip','Maximum post-onset analysis window (s); limits peaks used for steady-state estimation and crop')});

end
