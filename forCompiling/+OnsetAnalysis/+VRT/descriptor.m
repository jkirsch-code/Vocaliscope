function d = descriptor()
%DESCRIPTOR Returns specification for Vocal Rise Time (VRT) method
%   D = DESCRIPTOR() returns a struct with all metadata needed by the UI
%   and the compute engine.

d.name = 'Vocal Rise Time (Audio)';
d.acronym = 'VRT';
d.summary = 'Time from onset detection to when the RMS envelope reaches a steady-state fraction of the sustained amplitude.';
d.details = sprintf([ ...
    'Vocal Rise Time (VRT) measures the duration of the phonation onset ' ...
    'phase. It is defined as the time interval between the first detection ' ...
    'of phonation (via an energy-based voice activity detector) and the ' ...
    'point where the RMS envelope reaches a specified fraction (default 90%%) ' ...
    'of the steady-state amplitude. This captures how quickly the voice ' ...
    'reaches its full intensity after phonation begins.\n\n' ...
    'Algorithm: Energy-based VAD (Hann-windowed RMS envelope) -> noise floor ' ...
    'estimation from first N seconds -> threshold = noiseFloor * factor -> ' ...
    'first crossing = onset -> median RMS in post-onset VAD segment = ' ...
    'steady-state -> time to reach steadyStateFrac * steadyStateAmp = ' ...
    'VRT endpoint.\n\n' ...
    'Note: VRT uses the RMS envelope of the acoustic signal. The RMS ' ...
    'amplitude of a sinusoidal waveform is lower than its peak amplitude ' ...
    '(RMS = peak/sqrt(2)), so VRT and POT envelopes are not directly ' ...
    'comparable in amplitude.\n\n' ...
    'Validated for modal, breathy, and pressed phonation types. ' ...
    'Applicable to soft, hard, and breathy onsets.\n\n' ...
    'Minimum sample rate: 8 kHz.']);

d.requiredSignals = {'Audio'};
d.optionalSignals = {};
d.signalRoles = struct('Audio', 'Primary acoustic signal used for RMS envelope onset detection');
d.voiceTypes = {'modal', 'breathy', 'pressed'};
d.onsetTypes = {'soft', 'hard', 'breathy'};
d.validatedFor = 'Healthy adults (Bi et al. 2024, J. Voice) and disordered voices';
d.minFs_Hz = 8000;
d.algorithmDesc = 'Energy-based VAD (VOAT-inspired) + RMS envelope tracking with adaptive threshold';

d.params = struct(...
    'rmsWindow_s',       {struct('default',0.01, 'limits',[0.002 0.05], 'tooltip','Window length for RMS envelope (Hann window, periodic)')}, ...
    'noiseFloor_s',      {struct('default',0.05, 'limits',[0.01 0.2],  'tooltip','Duration at signal start used to estimate noise floor')}, ...
    'thresholdFactor',   {struct('default',3,    'limits',[1.5 10],    'tooltip','Noise floor multiplier for onset detection threshold')}, ...
    'steadyStateFrac',   {struct('default',0.9,  'limits',[0.5 1],     'tooltip','Fraction of steady-state amplitude defining VRT endpoint (0.9 = 90%)')}, ...
    'maxWindow_s',       {struct('default',0.3,  'limits',[0.05 2.0],  'tooltip','Maximum post-onset analysis window (s); limits region used for steady-state amplitude estimation')});

end
